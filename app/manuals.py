_NAV_ITEMS_BY_KEY = {item["key"]: item for item in NAV_ITEMS}


def get_manual(tool_key: str) -> dict | None:
    manual = MANUALS.get(tool_key)
    nav_item = _NAV_ITEMS_BY_KEY.get(tool_key)
    if manual is None or nav_item is None:
        return None
    return {
        "key": tool_key,
        "tool_label": nav_item["label"],
        "tool_href": nav_item["href"],
        **manual,
    }
